"""Review rules of the meclib workbench: conventions for STACK questions with meclib, checked
when a question is opened (Questions page, "Review"). Each finding has a key (rule[target]),
a level, a message and, if it can be fixed automatically, a fix that changes the question's
XML text (only the affected elements, as qfile does for edits).

Levels:
  required     Moodle refuses the question or it does not work (no automatic fix)
  recommended  meclib conventions (style guide, wiki pages of the feedback functions)
  hint         worth a look; a fix, if offered, is not preselected

The values follow the wiki: "Style Guide for Questions in Engineering Mechanics",
"MecLib Question Setup", "Multilingual questions", fb_unit, and decisions of the maintainer
(relative tolerance 0.005, no insert stars for number inputs, students must verify).

Rejected findings are recorded in the question's description field ("questiondescription",
internal, not shown to students) as readable lines:
    Generated by Meclib Workbench 2026-10-09 17:30
    Revised by Meclib Workbench 2026-10-09 17:42
    Review rejected: prt.tolerance[v_1], inputs.settings[S_v1]
"""

