# ---------------------------------------------------------------------- XML helpers
def _blocks(q, tag):
    return list(re.finditer(r"<%s>.*?</%s>" % (tag, tag), q, re.S))


def _named(q, tag, name):
    for m in _blocks(q, tag):
        if re.search(r"<name>%s</name>" % re.escape(name), m.group(0)):
            return m
    raise ValueError("%s %r not found" % (tag, name))


def _set_in(q, outer, name, tag, value):
    """<tag> inside the <outer> element named name (first occurrence: the element's own child)."""
    m = _named(q, outer, name)
    block, _ = qfile._replace_simple(m.group(0), tag, value)
    return q[:m.start()] + block + q[m.end():]


def _set_node(q, prt, node_index, tag, value):
    m = _named(q, "prt", prt)
    nodes = _blocks(m.group(0), "node")
    n = nodes[node_index]
    block, _ = qfile._replace_simple(n.group(0), tag, value)
    p = m.group(0)[:n.start()] + block + m.group(0)[n.end():]
    return q[:m.start()] + p + q[m.end():]


def _set_node_format(q, prt, node_index, branch, fmt):
    m = _named(q, "prt", prt)
    nodes = _blocks(m.group(0), "node")
    n = nodes[node_index]
    block = re.sub(r'<%sfeedback(\s+format="[^"]*")?\s*>' % branch, '<%sfeedback format="%s">' % (branch, fmt),
                   n.group(0), count=1)
    p = m.group(0)[:n.start()] + block + m.group(0)[n.end():]
    return q[:m.start()] + p + q[m.end():]


def _prt_html(q, prt):
    """All feedback branches of the PRT in format html (STACK wants one format for all nodes of a PRT)."""
    m = _named(q, "prt", prt)
    block = re.sub(r'<(true|false)feedback(\s+format="[^"]*")?\s*>', r'<\1feedback format="html">', m.group(0))
    return q[:m.start()] + block + q[m.end():]


def _set_node_text(q, prt, node_index, tag, value):
    m = _named(q, "prt", prt)
    nodes = _blocks(m.group(0), "node")
    n = nodes[node_index]
    block = qfile._replace_text_child(n.group(0), tag, value, qfile._newline(q))[0]
    p = m.group(0)[:n.start()] + block + m.group(0)[n.end():]
    return q[:m.start()] + p + q[m.end():]


def _set_prt_text(q, prt, tag, value):
    """<tag><text>value</text></tag> of the PRT named prt (e.g. its feedback variables)."""
    m = _named(q, "prt", prt)
    block = qfile._replace_text_child(m.group(0), tag, value, qfile._newline(q))[0]
    return q[:m.start()] + block + q[m.end():]


def _set_text(q, tag, value):
    return qfile._replace_text_child(q, tag, value, qfile._newline(q))[0]


def _set_head(q, tag, value):
    cut = min([i for i in (q.find("<input>"), q.find("<prt>")) if i >= 0] or [len(q)])
    head, _ = qfile._replace_simple(q[:cut], tag, value)
    return head + q[cut:]


def _t(el, path):
    return qfile._text(el, path)


def split_args(src):
    """Top level arguments of a Maxima argument list (without the parentheses)."""
    args, depth, cur, i = [], 0, "", 0
    while i < len(src):
        c = src[i]
        if c == '"':
            j = i + 1
            while j < len(src) and src[j] != '"':
                j += 2 if src[j] == "\\" else 1
            cur += src[i:j + 1]
            i = j + 1
            continue
        if c in "([{":
            depth += 1
        elif c in ")]}":
            if depth == 0:
                break
            depth -= 1
        if c == "," and depth == 0:
            args.append(cur.strip())
            cur = ""
        else:
            cur += c
        i += 1
    args.append(cur.strip())
    return args


# ---------------------------------------------------------------------- the question
class Q:
    """A question block and what the rules look at."""
    def __init__(self, block):
        self.block = block
        self.el = ET.fromstring(block)
        self.data = sq.question_data(self.el)
        self.qtext = self.data["questiontext"]
        self.qvars = self.data["questionvariables"]
        self.inputs = [{k: qfile._text(i, k) for k in ["name"] + qfile.INPUT_FIELDS} for i in self.el.findall("input")]
        self.prts = self.data["prts"]
        # inputs bound to a [[jsxgraph]] block: name -> JavaScript variable
        self.graphic = {}
        for m in re.finditer(r"\[\[\s*jsxgraph\b([^\]]*)\]\]", self.qtext):
            for a in re.finditer(r'input-ref-([A-Za-z0-9_]+)\s*=\s*["\']([^"\']*)["\']', m.group(1)):
                self.graphic[a.group(1)] = a.group(2)
        self.includes = sq.INCLUDE.findall(self.qvars)


def F(rule, target, level, title, message, fix=None, wiki=None, default=None):
    return {"rule": rule, "target": target, "key": "%s[%s]" % (rule, target) if target else rule,
            "level": level, "title": title, "message": message, "fix": fix, "wiki": wiki,
            "default": (level != "hint") if default is None else default}


# ---------------------------------------------------------------------- rules
def r_security(Q_):
    """Identifiers STACK refuses in a question (its security list: functions like system(),
    eval_string(), concat() of names ...): STACK does not save such a question. Checked: the model
    answers and texts (as the preview's check), the question variables and the feedback variables
    of the PRTs, statement by statement. Rename or replace the identifier."""
    out = []
    for place, msg in sq.security_findings(Q_.data).items():
        out.append(F("security", place, "required", "Identifier forbidden by STACK", place + ": " + msg))
    for k, (stmt, line, _i) in enumerate(sq.split_statements(Q_.qvars)):
        bad = sq.forbidden_identifiers(sq.strip_comments(stmt))
        if bad:
            out.append(F("security", "questionvariables line %d" % line, "required", "Identifier forbidden by STACK",
                         "question variables, line %d: %s" % (line, sq.forbidden_message(bad, "rename it"))))
    for prt in Q_.prts:
        for stmt, line, _i in sq.split_statements(prt["feedbackvariables"]):
            bad = sq.forbidden_identifiers(sq.strip_comments(stmt))
            if bad:
                out.append(F("security", "PRT %s line %d" % (prt["name"], line), "required",
                             "Identifier forbidden by STACK", "PRT %s, feedback variables, line %d: %s"
                             % (prt["name"], line, sq.forbidden_message(bad, "rename it"))))
    return out


STYLE_TYPO = re.compile(r"\bstyle\s*=\s*style\s*=\s*", re.I)


def r_style_typo(Q_):
    """A doubled style attribute style=style="..." in the question text or the general/specific
    feedback (a slip of older templates): browsers ignore the style, so e.g. the graphic no longer
    floats beside the text. The fix removes the duplicate."""
    out = []
    for field in ("questiontext", "generalfeedback", "specificfeedback"):
        text = Q_.data.get(field) or ""
        if not STYLE_TYPO.search(text):
            continue

        def fix(q, field=field):
            return _set_text(q, field, STYLE_TYPO.sub("style=", Q(q).data.get(field) or ""))
        out.append(F("layout.style-typo", field, "recommended", "Broken style attribute",
                     "%s: style=style=\"...\" - browsers ignore this style (the graphic no longer floats). "
                     "Remove the duplicate style=." % field, fix))
    return out


FLOAT_DIV = re.compile(r"""(<div\b[^>]*?\bstyle\s*=\s*)(["'])([^"']*)\2""", re.I)


def r_float_margin(Q_):
    """A block floating right or left (usually the graphic, <div style="float:right">) without a
    margin: the text runs into it. The fix adds the margin of the workbench template (right: 0 0
    0.5em 1.5em, left: 0 1.5em 0.5em 0). One finding per text; after the fix a new review finds
    the next block."""
    out = []
    for field in ("questiontext", "generalfeedback", "specificfeedback"):
        text = Q_.data.get(field) or ""
        for m in FLOAT_DIV.finditer(text):
            style = m.group(3)
            fl = re.search(r"float\s*:\s*(right|left)", style, re.I)
            if not fl or re.search(r"\bmargin", style, re.I):
                continue
            side = fl.group(1).lower()

            def fix(q, field=field, old=m.group(0), style=style, side=side, pre=m.group(1), quote=m.group(2)):
                text = Q(q).data.get(field) or ""
                new_style = style.rstrip().rstrip(";") + "; margin: %s;" % FLOAT_MARGIN[side]
                i = text.find(old)
                if i < 0:
                    raise ValueError("the <div> has changed")
                pre = STYLE_TYPO.sub("style=", pre)      # repairs style=style=" as well
                return _set_text(q, field, text[:i] + pre + quote + new_style + quote + text[i + len(old):])
            out.append(F("layout.float-margin", field, "recommended", "Distance between graphic and text",
                         "%s: the %s-aligned block (graphic) has no margin, the text runs into it. "
                         "Add margin: %s (as in the workbench template)." % (field, side, FLOAT_MARGIN[side]), fix))
            break      # one finding per text; after the fix a new review finds the next block
    return out


def uses_meclib_feedback(Q_):
    return any(re.search(r"meclib/[^\"]*/Maxima/fb_\w+\.mac", u) for u in Q_.includes)


def r_lang(Q_):
    """A question that uses meclib feedback functions (an fb_*.mac include) but declares no languages
    in the question text: STACK then shows the English texts of the feedback functions. The fix
    inserts the empty declaration [[lang code="de"]] [[/lang]][[lang code="other"]] [[/lang]]
    after the graphic (wiki "Multilingual questions")."""
    if not uses_meclib_feedback(Q_) or "[[lang" in Q_.qtext:
        return []

    def fix(q):
        text = Q(q).qtext
        m = re.search(r"\[\[\s*/jsxgraph\s*\]\]\s*</div>", text)
        if m:
            new = text[:m.end()] + "\n" + LANG_DECLARATION + text[m.end():]
        else:
            new = LANG_DECLARATION + "\n" + text
        return _set_text(q, "questiontext", new)
    return [F("lang.declaration", "questiontext", "recommended", "Language declaration for meclib feedback",
              "The question uses meclib feedback functions but declares no languages; STACK then shows "
              "their English texts. Insert the empty declaration %s (after the graphic)." % LANG_DECLARATION,
              fix, WIKI + "Multilingual-questions")]


def r_lang_includes(Q_):
    """Includes of the obsolete language-specific libraries fb_*_EN.mac / fb_*_DE.mac: the feedback
    functions are multilingual. The fix includes fb_*.mac instead."""
    out = []
    for url in Q_.includes:
        m = re.search(r"/(fb_\w+?)_(EN|DE)\.mac$", url)
        if not m:
            continue
        new_url = url[:m.start()] + "/" + m.group(1) + ".mac"

        def fix(q, url=url, new_url=new_url):
            return _set_text(q, "questionvariables", Q(q).qvars.replace(url, new_url))
        out.append(F("include.lang-specific", m.group(1) + "_" + m.group(2), "recommended",
                     "Language-specific library",
                     "%s_%s.mac is obsolete since the feedback functions are multilingual; include %s.mac."
                     % (m.group(1), m.group(2), m.group(1)), fix, WIKI + "Multilingual-questions"))
    return out


# Includes of meclib from a branch other than main (e.g. the dev branch while a feature is not
# merged yet): a reminder to switch back after the merge; the fix only after it, as main may not
# have the functions yet.
def r_include_branch(Q_):
    out = []
    for url in Q_.includes:
        m = re.match(r"(https://raw\.githubusercontent\.com/mkraska/meclib/)([^/]+)(/.*)$", url)
        if not m or m.group(2) == "main":
            continue
        new_url = m.group(1) + "main" + m.group(3)

        def fix(q, url=url, new_url=new_url):
            return _set_text(q, "questionvariables", Q(q).qvars.replace(url, new_url))
        out.append(F("include.branch", url.rsplit("/", 1)[-1], "hint", "Include from branch " + m.group(2),
                     "%s is included from the branch %s, not from main. Switch to main once %s is "
                     "merged into main (before that, main may lack functions the question uses)."
                     % (url.rsplit("/", 1)[-1], m.group(2), m.group(2)), fix))
    return out


