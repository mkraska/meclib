# ---------------------------------------------------------------------- XML helpers
def _blocks(q, tag):
    return list(re.finditer(r"<%s>.*?</%s>" % (tag, tag), q, re.S))


def _named(q, tag, name):
    for m in _blocks(q, tag):
        if re.search(r"<name>%s</name>" % re.escape(name), m.group(0)):
            return m
    raise ValueError("%s %r not found" % (tag, name))


def _set_in(q, outer, name, tag, value):
    """<tag> inside the <outer> element named name (first occurrence: the element's own child)."""
    m = _named(q, outer, name)
    block, _ = qfile._replace_simple(m.group(0), tag, value)
    return q[:m.start()] + block + q[m.end():]


def _set_node(q, prt, node_index, tag, value):
    m = _named(q, "prt", prt)
    nodes = _blocks(m.group(0), "node")
    n = nodes[node_index]
    block, _ = qfile._replace_simple(n.group(0), tag, value)
    p = m.group(0)[:n.start()] + block + m.group(0)[n.end():]
    return q[:m.start()] + p + q[m.end():]


def _set_node_format(q, prt, node_index, branch, fmt):
    m = _named(q, "prt", prt)
    nodes = _blocks(m.group(0), "node")
    n = nodes[node_index]
    block = re.sub(r'<%sfeedback(\s+format="[^"]*")?\s*>' % branch, '<%sfeedback format="%s">' % (branch, fmt),
                   n.group(0), count=1)
    p = m.group(0)[:n.start()] + block + m.group(0)[n.end():]
    return q[:m.start()] + p + q[m.end():]


def _set_text(q, tag, value):
    return qfile._replace_text_child(q, tag, value, qfile._newline(q))[0]


def _set_head(q, tag, value):
    cut = min([i for i in (q.find("<input>"), q.find("<prt>")) if i >= 0] or [len(q)])
    head, _ = qfile._replace_simple(q[:cut], tag, value)
    return head + q[cut:]


def _t(el, path):
    return qfile._text(el, path)


def split_args(src):
    """Top level arguments of a Maxima argument list (without the parentheses)."""
    args, depth, cur, i = [], 0, "", 0
    while i < len(src):
        c = src[i]
        if c == '"':
            j = i + 1
            while j < len(src) and src[j] != '"':
                j += 2 if src[j] == "\\" else 1
            cur += src[i:j + 1]
            i = j + 1
            continue
        if c in "([{":
            depth += 1
        elif c in ")]}":
            if depth == 0:
                break
            depth -= 1
        if c == "," and depth == 0:
            args.append(cur.strip())
            cur = ""
        else:
            cur += c
        i += 1
    args.append(cur.strip())
    return args


# ---------------------------------------------------------------------- the question
class Q:
    """A question block and what the rules look at."""
    def __init__(self, block):
        self.block = block
        self.el = ET.fromstring(block)
        self.data = sq.question_data(self.el)
        self.qtext = self.data["questiontext"]
        self.qvars = self.data["questionvariables"]
        self.inputs = [{k: qfile._text(i, k) for k in ["name"] + qfile.INPUT_FIELDS} for i in self.el.findall("input")]
        self.prts = self.data["prts"]
        # inputs bound to a [[jsxgraph]] block: name -> JavaScript variable
        self.graphic = {}
        for m in re.finditer(r"\[\[\s*jsxgraph\b([^\]]*)\]\]", self.qtext):
            for a in re.finditer(r'input-ref-([A-Za-z0-9_]+)\s*=\s*["\']([^"\']*)["\']', m.group(1)):
                self.graphic[a.group(1)] = a.group(2)
        self.includes = sq.INCLUDE.findall(self.qvars)


def F(rule, target, level, title, message, fix=None, wiki=None, default=None):
    return {"rule": rule, "target": target, "key": "%s[%s]" % (rule, target) if target else rule,
            "level": level, "title": title, "message": message, "fix": fix, "wiki": wiki,
            "default": (level != "hint") if default is None else default}


# ---------------------------------------------------------------------- rules
def r_security(Q_):
    out = []
    for place, msg in sq.security_findings(Q_.data).items():
        out.append(F("security", place, "required", "Identifier forbidden by STACK", place + ": " + msg))
    for k, (stmt, line, _i) in enumerate(sq.split_statements(Q_.qvars)):
        bad = sq.forbidden_identifiers(sq.strip_comments(stmt))
        if bad:
            out.append(F("security", "questionvariables line %d" % line, "required", "Identifier forbidden by STACK",
                         "question variables, line %d: %s" % (line, sq.forbidden_message(bad, "rename it"))))
    for prt in Q_.prts:
        for stmt, line, _i in sq.split_statements(prt["feedbackvariables"]):
            bad = sq.forbidden_identifiers(sq.strip_comments(stmt))
            if bad:
                out.append(F("security", "PRT %s line %d" % (prt["name"], line), "required",
                             "Identifier forbidden by STACK", "PRT %s, feedback variables, line %d: %s"
                             % (prt["name"], line, sq.forbidden_message(bad, "rename it"))))
    return out


STYLE_TYPO = re.compile(r"\bstyle\s*=\s*style\s*=\s*", re.I)


def r_style_typo(Q_):
    out = []
    for field in ("questiontext", "generalfeedback", "specificfeedback"):
        text = Q_.data.get(field) or ""
        if not STYLE_TYPO.search(text):
            continue

        def fix(q, field=field):
            return _set_text(q, field, STYLE_TYPO.sub("style=", Q(q).data.get(field) or ""))
        out.append(F("layout.style-typo", field, "recommended", "Broken style attribute",
                     "%s: style=style=\"...\" - browsers ignore this style (the graphic no longer floats). "
                     "Remove the duplicate style=." % field, fix))
    return out


FLOAT_DIV = re.compile(r"""(<div\b[^>]*?\bstyle\s*=\s*)(["'])([^"']*)\2""", re.I)


def r_float_margin(Q_):
    out = []
    for field in ("questiontext", "generalfeedback", "specificfeedback"):
        text = Q_.data.get(field) or ""
        for m in FLOAT_DIV.finditer(text):
            style = m.group(3)
            fl = re.search(r"float\s*:\s*(right|left)", style, re.I)
            if not fl or re.search(r"\bmargin", style, re.I):
                continue
            side = fl.group(1).lower()

            def fix(q, field=field, old=m.group(0), style=style, side=side, pre=m.group(1), quote=m.group(2)):
                text = Q(q).data.get(field) or ""
                new_style = style.rstrip().rstrip(";") + "; margin: %s;" % FLOAT_MARGIN[side]
                i = text.find(old)
                if i < 0:
                    raise ValueError("the <div> has changed")
                pre = STYLE_TYPO.sub("style=", pre)      # repairs style=style=" as well
                return _set_text(q, field, text[:i] + pre + quote + new_style + quote + text[i + len(old):])
            out.append(F("layout.float-margin", field, "recommended", "Distance between graphic and text",
                         "%s: the %s-aligned block (graphic) has no margin, the text runs into it. "
                         "Add margin: %s (as in the workbench template)." % (field, side, FLOAT_MARGIN[side]), fix))
            break      # one finding per text; after the fix a new review finds the next block
    return out


def uses_meclib_feedback(Q_):
    return any(re.search(r"meclib/[^\"]*/Maxima/fb_\w+\.mac", u) for u in Q_.includes)


def r_lang(Q_):
    if not uses_meclib_feedback(Q_) or "[[lang" in Q_.qtext:
        return []

    def fix(q):
        text = Q(q).qtext
        m = re.search(r"\[\[\s*/jsxgraph\s*\]\]\s*</div>", text)
        if m:
            new = text[:m.end()] + "\n" + LANG_DECLARATION + text[m.end():]
        else:
            new = LANG_DECLARATION + "\n" + text
        return _set_text(q, "questiontext", new)
    return [F("lang.declaration", "questiontext", "recommended", "Language declaration for meclib feedback",
              "The question uses meclib feedback functions but declares no languages; STACK then shows "
              "their English texts. Insert the empty declaration %s (after the graphic)." % LANG_DECLARATION,
              fix, WIKI + "Multilingual-questions")]


def r_lang_includes(Q_):
    out = []
    for url in Q_.includes:
        m = re.search(r"/(fb_\w+?)_(EN|DE)\.mac$", url)
        if not m:
            continue
        new_url = url[:m.start()] + "/" + m.group(1) + ".mac"

        def fix(q, url=url, new_url=new_url):
            return _set_text(q, "questionvariables", Q(q).qvars.replace(url, new_url))
        out.append(F("include.lang-specific", m.group(1) + "_" + m.group(2), "recommended",
                     "Language-specific library",
                     "%s_%s.mac is obsolete since the feedback functions are multilingual; include %s.mac."
                     % (m.group(1), m.group(2), m.group(1)), fix, WIKI + "Multilingual-questions"))
    return out


def _input_fix(name, changes):
    def fix(q):
        for k, v in changes.items():
            q = _set_in(q, "input", name, k, v)
        return q
    return fix


def r_graphic_inputs(Q_):
    out = []
    for inp in Q_.inputs:
        ref = Q_.graphic.get(inp["name"])
        if ref not in GRAPHIC_TARGETS:
            continue
        changes = {k: v for k, v in GRAPHIC_TARGETS[ref].items() if (inp.get(k) or "") != v}
        if changes:
            out.append(F("inputs.graphic", inp["name"], "recommended", "Settings of the graphic's input",
                         "Input %s (bound to the graphic as %s): %s." % (inp["name"], ref, ", ".join(
                             "%s %s → %s" % (FIELD_LABELS.get(k, k), inp.get(k) or "-", v) for k, v in changes.items())),
                         _input_fix(inp["name"], changes), WIKI + "MecLib-Question-Setup"))
        if not re.search(r"<p\s+hidden\s*>[^<]*\[\[\s*input:%s\s*\]\]" % re.escape(inp["name"]), Q_.qtext):
            out.append(F("inputs.graphic-visible", inp["name"], "hint", "Graphic input visible",
                         "[[input:%s]] is not inside <p hidden> ... </p>: students see the raw data "
                         "(fine while debugging)." % inp["name"]))
    return out


def r_input_settings(Q_):
    out = []
    has_fb_value = any("fb_value" in u for u in Q_.includes)
    for inp in Q_.inputs:
        if inp["name"] in Q_.graphic or inp["type"] not in INPUT_TARGETS:
            continue
        changes = {k: v for k, v in INPUT_TARGETS[inp["type"]].items() if (inp.get(k) or "") != v}
        if changes:
            out.append(F("inputs.settings", inp["name"], "recommended", "Input settings",
                         "Input %s (%s): %s." % (inp["name"], inp["type"], ", ".join(
                             "%s %s → %s" % (FIELD_LABELS.get(k, k), inp.get(k) or "-", v) for k, v in changes.items())),
                         _input_fix(inp["name"], changes), WIKI + "Style-Guide-for-Questions-in-Engineering-Mechanics"))
        hint = (inp.get("syntaxhint") or "").strip()
        want = SYNTAX_HINTS[inp["type"]]
        if hint != want and (not hint or hint.lower() in PLAIN_HINTS):
            if has_fb_value:
                out.append(F("inputs.syntaxhint", inp["name"], "recommended", "Multilingual syntax hint",
                             "Input %s: syntax hint %s → %s (German/English, from fb_value.mac)."
                             % (inp["name"], '"%s"' % hint if hint else "empty", want),
                             _input_fix(inp["name"], {"syntaxhint": want}), WIKI + "Multilingual-questions"))
            else:
                out.append(F("inputs.syntaxhint", inp["name"], "hint", "Multilingual syntax hint",
                             "Input %s: the multilingual hint %s needs fb_value.mac in the question variables."
                             % (inp["name"], want), None, WIKI + "Multilingual-questions"))
    return out


def _feedback(node):
    return (node.get("truefeedback") or "") + "\n" + (node.get("falsefeedback") or "")


def r_prts(Q_):
    out = []
    for prt in Q_.prts:
        P = prt["name"]
        texts = "".join(_feedback(n) for n in prt["nodes"])
        if prt["feedbackstyle"] != "2":
            if HTML_BLOCK.search(texts):
                out.append(F("prt.feedbackstyle", P, "hint", "PRT feedback style",
                             "PRT %s: feedback style is not compact, but its feedback contains HTML blocks "
                             "(<p>, <div>, lists), which need the standard style." % P))
            else:
                out.append(F("prt.feedbackstyle", P, "recommended", "PRT feedback style",
                             "PRT %s: feedback style %s → compact (2)." % (P, prt["feedbackstyle"]),
                             lambda q, P=P: _set_in(q, "prt", P, "feedbackstyle", "2"),
                             WIKI + "Style-Guide-for-Questions-in-Engineering-Mechanics"))
        if "fb_unit(" in texts and prt["autosimplify"]:
            out.append(F("prt.simp", P, "recommended", "PRT simplification with fb_unit",
                         "PRT %s uses fb_unit: switch simplification off, so that answers like 0*kg keep "
                         "their unit for the feedback%s." % (P, "" if not prt["feedbackvariables"].strip() else
                                                            " (check the feedback variables afterwards)"),
                         lambda q, P=P: _set_in(q, "prt", P, "autosimplify", "0"), WIKI + "fb_unit",
                         default=not prt["feedbackvariables"].strip()))
        for k, node in enumerate(prt["nodes"]):
            where = "%s node %d" % (P, k + 1)
            for br in ("true", "false"):
                fb = node.get(br + "feedback") or ""
                if fb.strip() and node.get(br + "format") != "html":
                    plain = re.sub(r"\{@.*?@\}", "", fb, flags=re.S).strip()
                    safe = not plain or not re.search(r"[\\*_#`\n]", plain)
                    out.append(F("prt.feedbackformat", "%s %s" % (where, br), "recommended",
                                 "Format of PRT feedback",
                                 "PRT %s, %s feedback: format %s → html; Markdown suppresses the yellow feedback "
                                 "background (reject only if the feedback is meant as a dynamic part of the question "
                                 "text)%s." % (where, br, node.get(br + "format"), "" if safe else
                                               "; the text contains Markdown-like characters, check it after the change"),
                                 lambda q, P=P, k=k, br=br: _set_node_format(q, P, k, br, "html"),
                                 WIKI + "Meclib-tutorial:-Add-Meclib-feedback-functions"))
            if re.search(r"\{@\s*fb_", _feedback(node)) and node.get("quiet") != "1":
                out.append(F("prt.quiet", where, "recommended", "Quiet answer test",
                             "PRT %s: the feedback comes from a meclib function; switch the answer test's own "
                             "feedback off (quiet)." % where,
                             lambda q, P=P, k=k: _set_node(q, P, k, "quiet", "1"),
                             WIKI + "Meclib-tutorial:-Add-Meclib-feedback-functions"))
            if node.get("answertest") in ("NumRelative", "UnitsRelative", "UnitsStrictRelative"):
                tol = (node.get("testoptions") or "").strip()
                if tol not in ACCEPTED_TOLERANCES:
                    out.append(F("prt.tolerance", where, "hint", "Relative tolerance",
                                 "PRT %s: %s with tolerance %s; standard is %s." % (
                                     where, node["answertest"], tol or "(empty)", TARGET_TOLERANCE),
                                 lambda q, P=P, k=k: _set_node(q, P, k, "testoptions", TARGET_TOLERANCE)))
    return out


def r_grade(Q_):
    grade = _t(Q_.el, "defaultgrade") or "0"
    try:
        zero = float(grade) == 0
    except ValueError:
        zero = False
    if Q_.prts and zero:
        return [F("grade.default", "", "recommended", "Default mark",
                  "The question has PRTs but default mark 0: it gives no points. Set it to 1.",
                  lambda q: _set_head(q, "defaultgrade", "1"))]
    return []


def _cas_sources(Q_):
    """(place, Maxima code) of the question: variables, feedback variables, CAS parts of texts."""
    yield "question variables", Q_.qvars
    for key in ("questiontext", "generalfeedback", "specificfeedback", "questionnote"):
        for part in sq.castext_cas_parts(Q_.data.get(key, "")):
            yield key, part
    for prt in Q_.prts:
        yield "PRT %s feedback variables" % prt["name"], prt["feedbackvariables"]
        for k, node in enumerate(prt["nodes"]):
            for part in sq.castext_cas_parts(_feedback(node)):
                yield "PRT %s node %d feedback" % (prt["name"], k + 1), part
            for f in ("sans", "tans"):
                yield "PRT %s node %d %s" % (prt["name"], k + 1, f), node.get(f) or ""


def r_literal_index(Q_):
    lists = OBJECT_LISTS + list(Q_.graphic)
    sub = re.compile(r"\b(%s)\s*\[\s*(\d+)\s*[\],]" % "|".join(map(re.escape, lists)))
    call = re.compile(r"\b(%s)\s*\(" % "|".join(INDEX_ARG))
    found = {}
    for place, code in _cas_sources(Q_):
        code = sq.strip_comments(code)
        for m in sub.finditer(code):
            found.setdefault(place, []).append("%s[%s]" % (m.group(1), m.group(2)))
        for m in call.finditer(code):
            args = split_args(code[m.end():])
            pos = INDEX_ARG[m.group(1)]
            if m.group(1) == "fb_fix12_name" and len(args) == 2:
                pos = 1
            if len(args) > pos and re.fullmatch(r"\d+", args[pos]):
                found.setdefault(place, []).append("%s(..., %s, ...)" % (m.group(1), args[pos]))
    return [F("index.literal", place, "hint", "Object index as a number",
              "%s: %s. Define a variable for each object index (e.g. i_A: 7; /* fix12 A */) and use it "
              "here; the numbers change when objects are inserted." % (place, ", ".join(dict.fromkeys(items))))
            for place, items in found.items()]


def r_tans_copy(Q_):
    out = []
    for inp in Q_.inputs:
        if Q_.graphic.get(inp["name"]) == "stateRef" and (inp.get("tans") or "").strip() == "init":
            out.append(F("tans.copy", inp["name"], "hint", "Model answer of the graphic",
                         "The model answer of %s is the initial state (init). Usually it is derived from it: "
                         "tansdata: copy(initdata) with changes, tans: stackjson_stringify(tansdata)." % inp["name"]))
    return out


# "locked" is a legacy state; it is replaced by "SHOW" (fb_system() counts only SHOW/show as
# shown). Offered only for object types with a regression test: types that appear with an
# explicit "SHOW" in a scene of tests/scenes/ (see state_show.json).
def show_tested():
    import glob, json
    types = set()
    for f in glob.glob(str(sq.REPO / "tests" / "scenes" / "*.json")):
        try:
            for o in json.load(open(f, encoding="utf-8")).get("initdata", []):
                if isinstance(o, list) and o and o[-1] == "SHOW":
                    types.add(o[0])
        except (OSError, ValueError):
            pass
    return types


OBJ_STATE = re.compile(r'\[\s*"(\w+)"(?:[^\[\]]|\[[^\[\]]*\])*?,\s*"locked"\s*\]')


def r_locked(Q_):
    found = [m for m in OBJ_STATE.finditer(sq.strip_comments(Q_.qvars))]
    if not found:
        return []
    out = []
    types = list(dict.fromkeys(m.group(1) for m in found))
    covered = show_tested()
    tested = [t for t in types if t in covered]
    for t in tested:
        def fix(q, t=t):
            qv = Q(q).qvars
            new = OBJ_STATE.sub(lambda m: m.group(0).replace('"locked"', '"SHOW"') if m.group(1) == t else m.group(0), qv)
            return _set_text(q, "questionvariables", new)
        out.append(F("state.locked", t, "recommended", 'Legacy state "locked"',
                     'Objects of type %s with the legacy state "locked": replace by "SHOW" (fb_system() counts only '
                     '"SHOW" as shown; regression test: tests/scenes/state_show.json).' % t, fix))
    untested = [t for t in types if t not in covered]
    if untested:
        out.append(F("state.locked", "untested", "hint", 'Legacy state "locked"',
                     'State "locked" in objects of type %s. Replacing it by "SHOW" is offered only for types with a '
                     'regression test for this (a scene in tests/scenes/ with the type in state "SHOW").' % ", ".join(untested)))
    return out


