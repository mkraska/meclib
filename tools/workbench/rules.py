            for name in re.findall(r"(?m)^([A-Za-z_%][A-Za-z0-9_%]*)\s*\([^()]*\)\s*:=", f.read_text(encoding="utf-8", errors="replace")):
                _MECLIB_FUNS.setdefault(name, f.name)
